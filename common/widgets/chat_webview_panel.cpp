void CHAT_WEBVIEW_PANEL::AddMessage( const wxString& aId, const wxString& aRole, 
                                      const wxString& aContent,
                                      const std::vector<ChatAttachment>& aAttachments )
{
    wxString script;
    
    if( aAttachments.empty() )
    {
        // No attachments - use simple format
        script = wxString::Format(
            wxT( "if(window.kichat){window.kichat.addMessage({id:'%s',role:'%s',content:'%s'});}" ),
            EscapeForJS( aId ),
            EscapeForJS( aRole ),
            EscapeForJS( aContent )
        );
    }
    else
    {
        // Build attachments JSON array
        wxString attachmentsJson = wxT( "[" );
        for( size_t i = 0; i < aAttachments.size(); i++ )
        {
            if( i > 0 )
                attachmentsJson += wxT( "," );
            
            const ChatAttachment& att = aAttachments[i];
            attachmentsJson += wxString::Format(
                wxT( "{name:'%s',type:'%s',data:'%s',size:%zu}" ),
                EscapeForJS( att.name ),
                EscapeForJS( att.mimeType ),
                EscapeForJS( att.base64Data ),
                att.size
            );
        }
        attachmentsJson += wxT( "]" );
        
        script = wxString::Format(
            wxT( "if(window.kichat){window.kichat.addMessage({id:'%s',role:'%s',content:'%s',attachments:%s});}" ),
            EscapeForJS( aId ),
            EscapeForJS( aRole ),
            EscapeForJS( aContent ),
            attachmentsJson
        );
    }
    
    if( m_bridgeReady.load() )
    {
        RunScriptFireAndForget( script );
    }
    else
    {
        m_pendingCommands.push_back( script );
    }
}


