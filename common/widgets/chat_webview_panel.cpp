wxString CHAT_WEBVIEW_PANEL::EscapeForJS( const wxString& aStr )
{
    wxString result;
    result.reserve( aStr.length() * 2 );
    
    for( wxChar c : aStr )
    {
        switch( c )
        {
        case '\\': result += wxT( "\\\\" ); break;
        case '\'': result += wxT( "\\'" ); break;
        case '"':  result += wxT( "\\\"" ); break;
        case '\n': result += wxT( "\\n" ); break;
        case '\r': result += wxT( "\\r" ); break;
        case '\t': result += wxT( "\\t" ); break;
        case '\0': result += wxT( "\\0" ); break;
        default:
            if( c < 32 )
            {
                result += wxString::Format( wxT( "\\x%02x" ), static_cast<int>( c ) );
            }
            else
            {
                result += c;
            }
            break;
        }
    }
    
    return result;
}


